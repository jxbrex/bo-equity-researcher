    rows = sd.scan_reports(str(tmp_path))
    assert sum(r["status"] == "duplicate" for r in rows) == 1
    assert sum(r["status"] == "demo" for r in rows) == 1
    assert sum(r["canonical"] for r in rows) == 2
    assert {r["report_date"] for r in rows if r["canonical"]} == {"2026-01-01", "2026-02-01"}


