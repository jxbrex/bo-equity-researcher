#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""audit_corpus 真实清单运行器回归（无网络；pytest 唯一入口）。"""
import json
import os
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from conftest import minimal_fill, write_fill


def _case_file(directory, name, valid=True):
    fill = minimal_fill(company=name)
    quote = write_fill({"price": fill["price"], "pe_ttm": fill["pe_ttm"]}, directory,
                       name=f"_em_{name}.json")
    fill["quote"] = {"source_file": os.path.basename(quote), "date": fill["date"]}
    if not valid:
        fill["price"] = "无法解析"
    return write_fill(fill, directory, name=f"_fill_{name}.json")


def test_run_manifest_passes_and_rejects_without_side_effects():
    from audit_corpus import run_manifest
    with tempfile.TemporaryDirectory() as d:
        good = _case_file(d, "good")
        bad = _case_file(d, "bad", valid=False)
        manifest = os.path.join(d, "manifest.json")
        with open(manifest, "w", encoding="utf-8") as fp:
            json.dump({"cases": [
                {"name": "pass-case", "fill": good, "expect": "pass",
                 "contains": "generated by render_report.py"},
                {"name": "reject-case", "fill": bad, "expect": "reject", "contains": "price"},
                {"name": "warning-case", "fill": good, "expect": "reject", "contains": "校验盲飞"},
            ]}, fp, ensure_ascii=False)
        out_dir = os.path.join(d, "results")
        results = run_manifest(manifest, out_dir)
        assert [item["ok"] for item in results] == [True, True, True]
        assert [item["actual"] for item in results] == ["pass", "reject", "reject"]
        assert os.path.exists(os.path.join(out_dir, "pass-case.html"))
        text_path = os.path.join(out_dir, "pass-case.txt")
        text = open(text_path, encoding="utf-8").read()
        assert "核心结论" in text and "<svg" not in text and "font-family" not in text
        assert not os.path.exists(os.path.join(out_dir, "reject-case.html"))
        assert os.path.exists(good) and os.path.exists(bad)
        assert os.path.exists(os.path.join(d, "_em_good.json"))
        assert os.path.exists(os.path.join(d, "_em_bad.json"))
        assert not os.path.exists(os.path.join(d, "_archive"))


def test_cli_rejects_expected_failure_that_actually_passes():
    with tempfile.TemporaryDirectory() as d:
        good = _case_file(d, "good")
        manifest = os.path.join(d, "manifest.json")
        with open(manifest, "w", encoding="utf-8") as fp:
            json.dump({"cases": [{"name": "must-reject", "fill": good, "expect": "reject"}]}, fp)
        script = os.path.join(os.path.dirname(__file__), "audit_corpus.py")
        result = subprocess.run([sys.executable, script, manifest, "--out", os.path.join(d, "out")],
                                capture_output=True, text=True, encoding="utf-8", errors="replace")
        assert result.returncode == 1, result.stdout + result.stderr
        assert "must-reject" in result.stdout and "预期 reject" in result.stdout


def test_unexpected_case_error_does_not_abort_remaining_cases_or_cwd_restore():
    from audit_corpus import run_manifest
    with tempfile.TemporaryDirectory() as d:
        good = _case_file(d, "good")
        manifest = os.path.join(d, "manifest.json")
        with open(manifest, "w", encoding="utf-8") as fp:
            json.dump({"cases": [
                {"name": "missing", "fill": os.path.join(d, "missing.json"), "expect": "pass"},
                {"name": "good", "fill": good, "expect": "pass"},
            ]}, fp)
        before = os.getcwd()
        results = run_manifest(manifest, os.path.join(d, "out"))
        assert os.getcwd() == before
        assert [item["actual"] for item in results] == ["error", "pass"]
        assert [item["ok"] for item in results] == [False, True]
        assert os.path.exists(os.path.join(d, "out", "results.json"))
        assert os.path.exists(os.path.join(d, "out", "good.html"))
