def _write_evidence(root, fill, specs=None, context=None):
    evidence_dir = root / "evidence"
    evidence_dir.mkdir(parents=True, exist_ok=True)
    specs = specs or _specs()
    facts = {}
    for dim, values in specs.items():
        facts[dim] = {name: {"value": value, "source_excerpt": "旧报告原文", "evidence_date": "2026-01-01"}
                      for name, value in values.items()}
    payload = {"report_date": fill["date"], "source_file": "old.html",
               "context": context or {"stock_type": "成长型", "industry_profile": "generic",
                                      "growth_tier": "mid", "report_date": fill["date"]},
               "facts": facts}
    path = evidence_dir / f"{fill['code']}_{fill['date']}.json"
    path.write_text(json.dumps(payload, ensure_ascii=False), encoding="utf-8")
    return evidence_dir


def _financial():
    names = ["profit_positive", "ocf_positive", "roa_improving", "cash_quality_ok",
             "long_debt_down", "short_cover_improving", "no_dilution",
             "gross_margin_improving", "asset_turnover_improving"]
    return {"status": "ok", "1D": {"kind": "generic_f", "f_items": {n: True for n in names},
                                   "liquidity": {"debt_ratio": 0.2, "short_cover": 2},
                                   "red_flags": {"receivables": False, "inventory": False,
                                                 "gross_margin_anomaly": False}},
            "1F": {"roic": 0.12, "wacc": 0.08, "incremental_roic": None,
                   "roic_basis": "latest", "roic_period_months": 12}, "coverage": {}, "sources": []}


def test_demo_duplicate_and_multi_version(tmp_path):
    fill = _fill()
    html = tmp_path / "测试股份-600000-6.0-5.0-2026-01-01.html"
    _html(html, "测试股份", "600000", 6.0, "2026-01-01")
    _html(tmp_path / "copy" / html.name, "测试股份", "600000", 6.0, "2026-01-01")
    later = tmp_path / "测试股份-600000-7.0-5.0-2026-02-01.html"
    _html(later, "测试股份", "600000", 7.0, "2026-02-01")
