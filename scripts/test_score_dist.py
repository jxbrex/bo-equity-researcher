def _html(path, company, code, quality, date, marker=True):
    text = (f'<h1>{company}（{code}）</h1><div>报告日期：{date}</div>'
            f'<div class="hero-track quality"><div class="s-value">{quality}</div></div>'
            f'<div class="hero-timing-mini">时机分 <span class="tv">5.0</span></div>'
            + ('<!-- generated by render_report.py -->' if marker else ''))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def _fill(company="测试股份", code="600000", date="2026-01-01", **over):
    fill = minimal_fill(company=company, code=code, date=date, stock_type="成长型", growth_tier="mid")
    fill.update(over)
    return fill


def _write_fill(root, fill, index=False):
    archive = root / "_archive"
    archive.mkdir(parents=True, exist_ok=True)
    path = archive / f"fill_{fill['company']}_{fill['code']}_{fill['date']}.json"
    path.write_text(json.dumps(fill, ensure_ascii=False), encoding="utf-8")
    if index:
        row = {"company": fill["company"], "code": fill["code"], "date": fill["date"],
               "html": f"{fill['company']}-{fill['code']}-6.0-5.0-{fill['date']}.html"}
        (archive / "_index.jsonl").write_text(json.dumps(row, ensure_ascii=False) + "\n", encoding="utf-8")
    return path


